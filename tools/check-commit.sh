#!/usr/bin/env bash
# dududu unified commit-message checker (R0.1).
#
# One validation function, four entry points:
#
#   bash tools/check-commit.sh --message "<header>"
#   bash tools/check-commit.sh --file <commit-message-file>
#   bash tools/check-commit.sh --range <base> <head>
#   bash tools/check-commit.sh --self-test
#
# --file is the commit-msg hook path: '#' comment lines are stripped exactly
# like git strips them after the hook. --range validates the RAW FIRST LINE of
# every non-merge commit in base..head (not git's %s, which joins wrapped
# subjects and could hide a broken header). Merge commits are skipped with an
# explicit SKIP line: their subjects are generated by git/GitHub, and the
# merged-main history that predates this convention is never re-judged because
# only base..head is ever inspected.
#
# Exit codes: 0 pass, 1 policy failure, 2 usage/internal error.
#
# Design notes (why bash, why one function): see
# docs/development/commit-convention.md and tools/tests/check-commit-test.sh,
# which was written first and defines this contract.

set -u -o pipefail
export LC_ALL=C.UTF-8

readonly PROGNAME="check-commit.sh"
readonly HEADER_MAX=72

# One structural pattern decides the shape; sub-checks refine the reasons so a
# single bad header can report every problem it has. The header itself is
# always a single physical line (newlines are stripped away before matching),
# so the ERE can never swallow a body.
readonly HEADER_RE='^(feat|fix|perf|refactor|test|build|ci|docs|chore|revert)\(([a-z0-9]+(-[a-z0-9]+)*)\)(!)?: (.+)$'
readonly ALLOWED_TYPES="feat fix perf refactor test build ci docs chore revert"

# Roadmap/project-management labels are not responsibility domains.
readonly FORBIDDEN_SCOPE_RES=(
  '^[rd][0-9]+$'          # r0, d2, d0, ...
  '^phase(-.+)?$'
  '^stage(-.+)?$'
  '^round(-.+)?$'
  '^step(-.+)?$'
  '^milestone(-.+)?$'
  '^sprint(-.+)?$'
)

# usage: validate_header <header> — appends human-readable errors to the
# global array ERRORS. The caller resets ERRORS. Empty header => single
# "empty" error.
validate_header() {
  local header="$1"

  if [ -z "$header" ]; then
    ERRORS+=("message is empty")
    return
  fi
  if [ -z "${header//[[:space:]]/}" ]; then
    ERRORS+=("message is empty")
    return
  fi

  if [[ $header == [[:space:]]* ]]; then
    ERRORS+=("header starts with whitespace")
  fi
  if [[ $header == *$'\r' ]]; then
    ERRORS+=("header ends with a carriage return (CRLF line endings? use LF)")
  fi
  if [[ $header =~ [[:space:]]$ ]]; then
    ERRORS+=("header ends with whitespace")
  fi

  local stripped="${header%"${header##*[![:space:]]}"}" # right-trimmed view
  if [ "${#header}" -gt "$HEADER_MAX" ]; then
    ERRORS+=("header is ${#header} characters; maximum is $HEADER_MAX")
  fi

  local type scope subject
  if [[ ! $stripped =~ $HEADER_RE ]]; then
    ERRORS+=("expected '<type>(<scope>): <subject>' or '<type>(<scope>)!: <subject>'; allowed types: $ALLOWED_TYPES")
    return
  fi
  type="${BASH_REMATCH[1]}"
  scope="${BASH_REMATCH[2]}"
  subject="${BASH_REMATCH[5]}"

  local re
  for re in "${FORBIDDEN_SCOPE_RES[@]}"; do
    if [[ $scope =~ $re ]]; then
      ERRORS+=("scope '$scope' is a roadmap/phase label; use the responsibility domain the change touches")
      break
    fi
  done

  if [[ ! $subject =~ ^[a-z0-9] ]]; then
    ERRORS+=("subject must begin with a lowercase letter or digit")
  fi
  if [[ $subject == *. || $subject == *。 ]]; then
    ERRORS+=("subject must not end with a full stop")
  fi
}

# usage: validate_text_bytes <string> — appends an error when the string
# carries control characters other than TAB/LF/CR. wc -c is used because
# command substitution silently drops NUL bytes.
validate_text_bytes() {
  local rest
  rest="$(printf '%s' "$1" | LC_ALL=C tr -d '\11\12\15\40-\176\200-\377' | LC_ALL=C wc -c)"
  if [ "$rest" -gt 0 ]; then
    ERRORS+=("message contains non-text control characters")
  fi
}

# usage: header_of <content> — skips leading blank lines, prints the first
# remaining line, sets HAS_CONTENT=0/1. Handles content without a trailing
# newline (`read` still yields the final partial line).
HAS_CONTENT=1
header_of() {
  local content="$1" line
  HAS_CONTENT=1
  while IFS= read -r line || [ -n "$line" ]; do
    if [ -n "$line" ]; then
      printf '%s' "$line"
      return
    fi
  done <<< "$content"
  HAS_CONTENT=0
  printf ''
}

report_errors() {
  local label="$1" header="$2" e
  for e in "${ERRORS[@]}"; do
    printf 'ERROR: %s: %s\n' "$label" "$e" >&2
  done
  printf '       got: %s\n' "$header" >&2
}

# usage: check_message <raw-message> <label> — the single entry point shared
# by every mode. Exit 0 pass, 1 reject.
check_message() {
  local raw="$1" label="$2" header
  ERRORS=()
  validate_text_bytes "$raw" "$label"
  header="$(header_of "$raw")"
  validate_header "$header"
  if [ "${#ERRORS[@]}" -gt 0 ]; then
    report_errors "$label" "$header"
    return 1
  fi
  printf 'PASS: %s: %s\n' "$label" "$header"
  return 0
}

check_file() {
  local path="$1" label="${LABEL:-commit message file}" line filtered=""
  if [ ! -f "$path" ]; then
    printf "ERROR: %s: cannot read message file: %s\n" "$label" "$path" >&2
    return 1
  fi
  # Screen the raw bytes first: NUL and other control bytes never survive
  # command substitution, so they must be caught in the file itself.
  local bad
  bad="$(LC_ALL=C tr -d '\11\12\15\40-\176\200-\377' < "$path" | LC_ALL=C wc -c)"
  if [ "$bad" -gt 0 ]; then
    printf 'ERROR: %s: message file contains non-text control characters\n' "$label" >&2
    return 1
  fi
  # Strip '#' comment lines exactly like git strips them after this hook runs.
  while IFS= read -r line || [ -n "$line" ]; do
    [[ $line == '#'* ]] && continue
    filtered+="$line"$'\n'
  done < "$path"
  check_message "$filtered" "$label"
}

verify_commit_ref() {
  local ref="$1"
  if ! git rev-parse --verify --quiet "${ref}^{commit}" >/dev/null 2>&1; then
    printf "ERROR: cannot resolve ref '%s' as a commit (unknown revision; fetch first?)\n" "$ref" >&2
    return 1
  fi
}

check_range() {
  local base="$1" head="$2" sha body header bad=0 n=0 merges=0
  verify_commit_ref "$base" || return 1
  verify_commit_ref "$head" || return 1

  local commits
  if ! commits="$(git rev-list --reverse --no-merges "$base..$head")"; then
    printf 'ERROR: git rev-list failed for %s..%s\n' "$base" "$head" >&2
    return 1
  fi

  if [ -z "$commits" ]; then
    printf 'PASS: NO_NEW_COMMITS: no commits in %s..%s; nothing to validate\n' "$base" "$head"
    return 0
  fi

  if merges="$(git rev-list --merges "$base..$head")"; [ -n "$merges" ]; then
    local msha msubj
    while IFS= read -r msha; do
      [ -n "$msha" ] || continue
      msubj="$(git show -s --format=%s "$msha")"
      printf 'SKIP: merge commit %s (subject policy not applied): %s\n' "${msha:0:12}" "$msubj"
    done <<< "$merges"
  fi

  while IFS= read -r sha; do
    [ -n "$sha" ] || continue
    body="$(git show -s --format=%B "$sha")"
    header="$(header_of "$body")"
    ERRORS=()
    validate_text_bytes "$body" "commit ${sha:0:12}"
    validate_header "$header"
    if [ "${#ERRORS[@]}" -gt 0 ]; then
      report_errors "commit ${sha:0:12}" "$header"
      bad=1
    else
      printf 'PASS: commit %s: %s\n' "${sha:0:12}" "$header"
      n=$((n + 1))
    fi
  done <<< "$commits"

  if [ "$bad" -ne 0 ]; then
    printf 'ERROR: commit convention violations in %s..%s\n' "$base" "$head" >&2
    return 1
  fi
  printf 'PASS: %d commit(s) validated in %s..%s\n' "$n" "$base" "$head"
  return 0
}

self_test() {
  local -a valid invalid
  valid=(
    "feat(adapter): add native filesystem wrapper"
    "fix(sdk): prevent stale archive reuse"
    "perf(uring): reduce completion dispatch cost"
    "refactor(oracle): split result comparison from io capture"
    "test(oracle): detect bypassed filesystem reads"
    "build(cmake): isolate SDK build profiles"
    "ci(repo): add lightweight policy validation"
    "docs(bench): describe benchmark admission"
    "chore(repo): configure lefthook"
    "revert(adapter): restore direct read path"
    "feat(sdk)!: restructure SDK layout"
    "fix(duckdb): 3x slower scan fixed by cache pinning"
    "feat(native-wrapper): add adapter shim"
    "feat(uring): x x x x x x x x x x x x x x x x x x x x x x x x x x x x 599"
    "$(printf 'feat(sdk)!: restructure SDK layout\n\nBREAKING CHANGE: consumers must re-run the sync step.')"
  )
  invalid=(
    "foo(repo): add thing"
    "featx(repo): add thing"
    "Feat(repo): add thing"
    "feat: add thing"
    "feat!: add thing"
    "feat(): add thing"
    "ci feat: add thing"
    "chore/fix(repo): add thing"
    "test+fix(repo): add thing"
    "feat(r0): add thing"
    "feat(d2): add thing"
    "feat(r1): add thing"
    "docs(phase-1): add thing"
    "chore(stage-2): add thing"
    "test(round-3): add thing"
    "feat(Repo): add thing"
    "feat(native_wrapper): add thing"
    "feat(-repo): add thing"
    "feat(repo-): add thing"
    "feat(repo):"
    "feat(repo) add thing"
    "feat(repo): Add thing"
    "feat(repo): add thing."
    "feat(repo): 加个功能。"
    "feat(repo):  add thing"
    "feat(repo): add thing "
    " feat(repo): add thing"
    "feat(repo): x x x x x x x x x x x x x x x x x x x x x x x x x x x x x 600"
    ""
    "   "
    "$(printf '\n\n\n')"
    "$(printf 'not a conventional header\nfeat(repo): decoy')"
    "$(printf 'feat(repo): bad period.\nfeat(repo): decoy')"
    "$(printf 'feat(repo): add \x01 thing')"
    "$(printf 'feat(repo): add thing\r')"
  )

  local failures=0 m
  for m in "${valid[@]}"; do
    if ! check_message "$m" "self-test" >/dev/null; then
      printf 'ERROR: self-test: valid message rejected: %q\n' "$m" >&2
      failures=$((failures + 1))
    fi
  done
  for m in "${invalid[@]}"; do
    if check_message "$m" "self-test" >/dev/null 2>&1; then
      printf 'ERROR: self-test: invalid message accepted: %q\n' "$m" >&2
      failures=$((failures + 1))
    fi
  done

  # --file path: comment stripping and byte screening share the same function.
  local tmp
  tmp="$(mktemp "${TMPDIR:-/tmp}/dududu-selftest.XXXXXX")"
  printf '# comment line, stripped like git does\nfeat(adapter): add native filesystem wrapper\n\nbody\n' > "$tmp"
  if ! check_file "$tmp" "self-test" >/dev/null; then
    printf 'ERROR: self-test: valid message file rejected\n' >&2
    failures=$((failures + 1))
  fi
  printf 'fix: no scope\n' > "$tmp"
  if check_file "$tmp" "self-test" >/dev/null 2>&1; then
    printf 'ERROR: self-test: invalid message file accepted\n' >&2
    failures=$((failures + 1))
  fi
  rm -f "$tmp"

  if [ "$failures" -gt 0 ]; then
    printf 'ERROR: self-test: %d failure(s)\n' "$failures" >&2
    return 1
  fi
  printf 'PASS: self-test (%d valid, %d invalid cases)\n' "${#valid[@]}" "${#invalid[@]}"
  return 0
}

usage() {
  cat >&2 <<EOF
usage: $PROGNAME (--message "<header>" | --file <path> | --range <base> <head> | --self-test)
                 [--label <name>]

  --message <text>   validate one raw message (header = first line)
  --file <path>      validate a commit-message file ('#' comments stripped)
  --range <b> <h>    validate every non-merge commit in b..h (git context)
  --self-test        run the built-in valid/invalid corpus
  --label <name>     diagnostics label (default: "message")

exit codes: 0 pass, 1 policy failure, 2 usage error
EOF
}

MODE=""
RANGE_BASE=""
RANGE_HEAD=""
LABEL="message"
while [ $# -gt 0 ]; do
  case "$1" in
    --message) [ $# -ge 2 ] || { usage; exit 2; }; MODE=message; MSG_VALUE="$2"; shift 2 ;;
    --file)    [ $# -ge 2 ] || { usage; exit 2; }; MODE=file; FILE_VALUE="$2"; shift 2 ;;
    --range)   [ $# -ge 3 ] || { usage; exit 2; }; MODE=range; RANGE_BASE="$2"; RANGE_HEAD="$3"; shift 3 ;;
    --self-test) MODE=self-test; shift ;;
    --label)   [ $# -ge 2 ] || { usage; exit 2; }; LABEL="$2"; shift 2 ;;
    -h|--help) usage; exit 0 ;;
    *) printf 'ERROR: unknown argument: %s\n' "$1" >&2; usage; exit 2 ;;
  esac
done

case "$MODE" in
  message)  check_message "$MSG_VALUE" "$LABEL" ;;
  file)     check_file "$FILE_VALUE" "$LABEL" ;;
  range)    check_range "$RANGE_BASE" "$RANGE_HEAD" ;;
  self-test) self_test ;;
  *)        usage; exit 2 ;;
esac
exit $?
